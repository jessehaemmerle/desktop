def main():
    for name, values in VARIANTS.items():
        out = ROOT / "data" / "themes" / name / "gtk-3.0" / "gtk.css"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(CSS.substitute(values, name=name), encoding="utf-8")
        index = out.parent.parent / "index.theme"
        if not index.exists():
            index.write_text("[Desktop Entry]\nType=X-GNOME-Metatheme\nName=%s\nEncoding=UTF-8\n\n"
                             "[X-GNOME-Metatheme]\nGtkTheme=%s\n" % (name, name), encoding="utf-8")
        if name in ("Tenwin-Dark", "Tenwin-Contrast"):
            (out.parent / "gtk-dark.css").write_text('@import url("gtk.css");\n', encoding="utf-8")
        elif name == "Tenwin-Contrast-White":
            (out.parent / "gtk-dark.css").write_text('@import url("../../Tenwin-Contrast/gtk-3.0/gtk.css");\n',
                                                      encoding="utf-8")
        else:
            (out.parent / "gtk-dark.css").write_text('@import url("../../Tenwin-Dark/gtk-3.0/gtk.css");\n',
                                                      encoding="utf-8")
    print("GTK themes written")


if __name__ == "__main__":
    main()
