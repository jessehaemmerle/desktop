BTN_W, BTN_H = 26, 30


def glyph(kind, color):
    cx, cy = BTN_W / 2, BTN_H / 2
    s = 5  # half glyph size -> 10px glyphs
    if kind == "iconify":
        return f'<path d="M{cx - s} {cy + .5}h{2 * s}" stroke="{color}" stroke-width="1"/>'
    if kind == "max":
        return (f'<rect x="{cx - s + .5}" y="{cy - s + .5}" width="{2 * s - 1}" height="{2 * s - 1}" '
                f'fill="none" stroke="{color}" stroke-width="1"/>')
    if kind == "max_toggled":
        return (f'<rect x="{cx - s + .5}" y="{cy - s + 2.5}" width="{2 * s - 3}" height="{2 * s - 3}" '
                f'fill="none" stroke="{color}" stroke-width="1"/>'
                f'<path d="M{cx - s + 2.5} {cy - s + 2.5}V{cy - s + .5}H{cx + s - .5}V{cy + s - 2.5}H{cx + s - 2.5}" '
                f'fill="none" stroke="{color}" stroke-width="1"/>')
    if kind == "close":
        return (f'<path d="M{cx - s} {cy - s}L{cx + s} {cy + s}M{cx + s} {cy - s}L{cx - s} {cy + s}" '
                f'stroke="{color}" stroke-width="1.1"/>')
    if kind == "menu":
        return ""
    raise ValueError(kind)


def button_svg(kind, fg, bg=None):
    rect = f'<rect width="{BTN_W}" height="{BTN_H}" fill="{bg}"/>' if bg else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{BTN_W}" height="{BTN_H}" '
            f'viewBox="0 0 {BTN_W} {BTN_H}" shape-rendering="crispEdges">{rect}{glyph(kind, fg)}</svg>')


