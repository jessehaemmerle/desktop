def sym(body, fill=False):
    style = 'fill="#bebebe"' if fill else 'fill="none" stroke="#bebebe" stroke-width="1" stroke-linecap="round" stroke-linejoin="round"'
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="16" height="16" viewBox="0 0 16 16">'
            f'<g {style}>{body}</g></svg>')


def wifi(level):
    arcs = []
    for i, r in enumerate((4.5, 8, 11.5)):
        opacity = 1 if i < level else 0.3
        a = math.radians(45)
        x1, y1 = 8 - r * math.sin(a), 14 - r * math.cos(a)
        x2, y2 = 8 + r * math.sin(a), 14 - r * math.cos(a)
        arcs.append(f'<path opacity="{opacity}" d="M{x1:.2f} {y1:.2f}A{r} {r} 0 0 1 {x2:.2f} {y2:.2f}"/>')
    return sym("".join(arcs) + '<circle cx="8" cy="13.5" r="0.9" fill="#bebebe"/>')


def volume(level):
    speaker = '<path d="M2 6h2.5L8 3v10l-3.5-3H2z"/>'
    waves = ""
    if level == "muted":
        waves = '<path d="M10.5 6l4 4M14.5 6l-4 4"/>'
    else:
        radii = {"low": [2.5], "medium": [2.5, 5], "high": [2.5, 5, 7.5]}[level]
        for r in radii:
            waves += f'<path d="M{8 + r * 0.6:.2f} {8 - r * 0.8:.2f}A{r} {r} 0 0 1 {8 + r * 0.6:.2f} {8 + r * 0.8:.2f}"/>'
    return sym(speaker + waves)


def battery(percent, charging=False):
    width = max(0.0, 10.0 * percent / 100)
    fill = f'<rect x="2.5" y="6.5" width="{width:.1f}" height="3" fill="#bebebe" stroke="none"/>' if width else ""
    bolt = '<path d="M8.5 4.5L6 8.5h3L7.5 12" stroke-width="1"/>' if charging else ""
    return sym('<rect x="1.5" y="5.5" width="12" height="5" rx="0.5"/><path d="M14.5 7v2"/>' + fill + bolt)


