def _(text):
    # Imported lazily so that the language setting is respected.
    from tenwin.i18n import _ as gettext
    return gettext(text)


def N_(text):
    return text


def ctl_path():
    path = paths.binary(CTL)
    return path


def theme_name(settings):
    return "Tenwin-Dark" if settings["appearance.app_mode"] == "dark" else "Tenwin"


def labwc_theme_name(settings):
    if settings["appearance.accent_on_titlebars"] and write_accent_theme(settings):
        return "Tenwin-Accent"
    return theme_name(settings)


def rc_xml(settings):
    ctl = ctl_path()
    lines = ['<?xml version="1.0"?>',
             "<!-- Generated by Tenwin. Changes are overwritten; use the Tenwin settings. -->",
             "<labwc_config>",
             "  <core><decoration>server</decoration><gap>0</gap></core>",
             "  <placement><policy>cascade</policy></placement>",
             "  <theme>",
             "    <name>%s</name>" % labwc_theme_name(settings),
             "    <cornerRadius>0</cornerRadius>",
             "    <keepBorder>yes</keepBorder>"]
    for place in ("ActiveWindow", "InactiveWindow", "MenuItem", "OnScreenDisplay"):
        lines.append('    <font place="%s"><name>Selawik</name><size>10</size></font>' % place)
    lines += ["  </theme>",
              '  <windowSwitcher show="yes" preview="no" outlines="yes">',
              '    <fields><field content="title" width="100%" /></fields>',
              "  </windowSwitcher>",
              "  <resistance><screenEdgeStrength>20</screenEdgeStrength>"
              "<windowEdgeStrength>0</windowEdgeStrength></resistance>",
              '  <resize popupShow="Never" />',
              "  <focus><followMouse>no</followMouse><raiseOnFocus>no</raiseOnFocus></focus>",
              "  <snapping><range>8</range><topMaximize>yes</topMaximize>"
              "<notifyClient>always</notifyClient></snapping>"]

    count = max(1, min(10, int(settings["desktops.count"])))
    lines.append("  <desktops><popupTime>800</popupTime><names>")
    for n in range(1, count + 1):
        lines.append("    <name>%s</name>" % escape(_("Desktop %d") % n))
    lines.append("  </names></desktops>")

    lines.append('  <keyboard><numlock>%s</numlock><layoutScope>global</layoutScope>'
                 % ("on" if settings["input.numlock"] else "off"))
    lines.append("    <repeatRate>%d</repeatRate><repeatDelay>%d</repeatDelay>"
                 % (settings["input.repeat_rate"], settings["input.repeat_delay"]))
    for key, command in CTL_KEYBINDS:
        lines.append('    <keybind key=%s><action name="Execute" command=%s /></keybind>'
                     % (quoteattr(key), quoteattr("%s %s" % (ctl, command))))
    for key, actions in LABWC_KEYBINDS:
        cancel = '<action name="Execute" command=%s />' % quoteattr("%s cancel" % ctl)
        body = "".join(([cancel] if key.startswith(("W-", "C-W")) else []) + actions)
        lines.append("    <keybind key=%s>%s</keybind>" % (quoteattr(key), body))
    lines.append("  </keyboard>")

    lines.append("  <mouse><default />")
    # Win10: right click on title shows the window menu, double click maximises.
    lines.append('    <context name="Title">'
                 '<mousebind button="Right" action="Click"><action name="ShowMenu" menu="client-menu" /></mousebind>'
                 '<mousebind button="Left" action="DoubleClick"><action name="ToggleMaximize" /></mousebind>'
                 "</context>")
    # No shading on titlebar scroll and no root menu (the desktop handles clicks).
    lines.append('    <context name="TitleBar">'
                 '<mousebind direction="Up" action="Scroll"><action name="None" /></mousebind>'
                 '<mousebind direction="Down" action="Scroll"><action name="None" /></mousebind>'
                 "</context>")
    lines.append('    <context name="Root">'
                 '<mousebind button="Left" action="Press"><action name="None" /></mousebind>'
                 '<mousebind button="Right" action="Press"><action name="None" /></mousebind>'
                 '<mousebind button="Middle" action="Press"><action name="None" /></mousebind>'
                 '<mousebind direction="Up" action="Scroll"><action name="None" /></mousebind>'
                 '<mousebind direction="Down" action="Scroll"><action name="None" /></mousebind>'
                 "</context>")
    lines.append("  </mouse>")

    def yn(value):
        return "yes" if value else "no"

    lines += ["  <libinput>",
              '    <device category="default">',
              "      <naturalScroll>%s</naturalScroll>" % yn(settings["input.natural_scroll"]),
              "      <leftHanded>%s</leftHanded>" % yn(settings["input.left_handed"]),
              "      <pointerSpeed>%.2f</pointerSpeed>" % float(settings["input.pointer_speed"]),
              "      <tap>%s</tap>" % yn(settings["input.tap_to_click"]),
              "      <disableWhileTyping>yes</disableWhileTyping>",
              "    </device>",
              "  </libinput>",
              "  <windowRules>",
              # Our own dialogs that must not appear in the window switcher.
              '    <windowRule identifier="org.tenwin.Shell*" skipTaskbar="yes" skipWindowSwitcher="yes" />',
              "  </windowRules>",
              "</labwc_config>"]
    return "\n".join(lines) + "\n"


def menu_xml():
    items = [
        (N_("Restore"), '<action name="ToggleMaximize" />'),
        (N_("Move"), '<action name="Move" />'),
        (N_("Size"), '<action name="Resize" />'),
        (N_("Minimize"), '<action name="Iconify" />'),
        (N_("Maximize"), '<action name="ToggleMaximize" />'),
        (N_("Always on top"), '<action name="ToggleAlwaysOnTop" />'),
        (N_("Move to next desktop"), '<action name="SendToDesktop" to="right" follow="no" />'),
    ]
    out = ['<?xml version="1.0" encoding="UTF-8"?>', "<openbox_menu>",
           '  <menu id="client-menu">']
    for label, action in items:
        out.append("    <item label=%s>%s</item>" % (quoteattr(_(label)), action))
    out.append("    <separator />")
    out.append("    <item label=%s><action name=\"Close\" /></item>"
               % quoteattr(_("Close") + "\tAlt+F4"))
    out += ["  </menu>", '  <menu id="root-menu"></menu>', "</openbox_menu>"]
    return "\n".join(out) + "\n"


def environment(settings):
    env = {
        "XDG_CURRENT_DESKTOP": "Tenwin:wlroots",
        "XDG_SESSION_DESKTOP": "tenwin",
        "XKB_DEFAULT_LAYOUT": settings["input.keyboard_layouts"] or "us",
        "XCURSOR_THEME": "DMZ-White",
        "XCURSOR_SIZE": str(settings["appearance.cursor_size"]),
        "MOZ_ENABLE_WAYLAND": "1",
        "QT_QPA_PLATFORM": "wayland;xcb",
        "QT_QPA_PLATFORMTHEME": "gtk3",
        "_JAVA_AWT_WM_NONREPARENTING": "1",
        "SDL_VIDEODRIVER": "wayland,x11",
    }
    if settings["input.keyboard_variant"]:
        env["XKB_DEFAULT_VARIANT"] = settings["input.keyboard_variant"]
    layouts = (settings["input.keyboard_layouts"] or "").split(",")
    if len(layouts) > 1:
        # Win+Space switches the input language, like on Windows 10.
        env["XKB_DEFAULT_OPTIONS"] = "grp:win_space_toggle"
    return "".join("%s=%s\n" % item for item in env.items())


def autostart():
    return "#!/bin/sh\n# Generated by Tenwin.\n%s --autostart &\n" % paths.binary("tenwin-session")


def themerc_override(settings):
    """Active window border in the accent colour, like Windows 10."""
    accent = settings["appearance.accent"]
    lines = ["# Generated by Tenwin.",
             "window.active.border.color: %s" % accent,
             "window.active.indicator.toggled-keybind.color: %s" % accent]
    return "\n".join(lines) + "\n"


def write_accent_theme(settings):
    """Create ~/.local/share/themes/Tenwin-Accent: titlebars in the accent colour.

    labwc's SVG buttons carry their own colours, so the base theme is copied
    and recoloured instead of using themerc-override.
    """
    from tenwin.theme import luminance

    base_name = "Tenwin-Dark" if settings["appearance.app_mode"] == "dark" else "Tenwin"
    source = None
    for root in _theme_roots():
        candidate = os.path.join(root, base_name, "openbox-3")
        if os.path.isdir(candidate):
            source = candidate
            break
    if source is None:
        return False
    accent = settings["appearance.accent"]
    fg = "#000000" if luminance(accent) > 0.4 else "#ffffff"
    base_fg = "#ffffff" if base_name == "Tenwin-Dark" else "#000000"
    data_home = os.environ.get("XDG_DATA_HOME") or os.path.expanduser("~/.local/share")
    target = os.path.join(data_home, "themes", "Tenwin-Accent", "openbox-3")
    os.makedirs(target, exist_ok=True)
    for name in os.listdir(source):
        with open(os.path.join(source, name), encoding="utf-8") as fh:
            content = fh.read()
        if name == "themerc":
            content += ("window.active.title.bg.color: %s\n"
                        "window.active.label.text.color: %s\n"
                        "window.active.button.unpressed.image.color: %s\n" % (accent, fg, fg))
        elif name.endswith("-active.svg") and not name.startswith("close_hover"):
            if "_hover" in name:
                hover = "rgba(255,255,255,0.2)" if fg == "#ffffff" else "rgba(0,0,0,0.12)"
                content = content.replace('fill="#e5e5e5"', 'fill="%s"' % hover)
                content = content.replace('fill="#404040"', 'fill="%s"' % hover)
            content = content.replace('stroke="%s"' % base_fg, 'stroke="%s"' % fg)
        with open(os.path.join(target, name), "w", encoding="utf-8") as fh:
            fh.write(content)
    return True


def _theme_roots():
    data_home = os.environ.get("XDG_DATA_HOME") or os.path.expanduser("~/.local/share")
    roots = [os.path.join(data_home, "themes"), str(paths.DATA_DIR / "themes")]
    for d in (os.environ.get("XDG_DATA_DIRS") or "/usr/local/share:/usr/share").split(":"):
        roots.append(os.path.join(d, "themes"))
    return [r for r in roots if "Tenwin-Accent" not in r]


def write_labwc_config(settings=None):
    settings = settings or load_file()
    target = paths.LABWC_CONFIG_DIR
    target.mkdir(parents=True, exist_ok=True)
    files = {
        "rc.xml": rc_xml(settings),
        "menu.xml": menu_xml(),
        "environment": environment(settings),
        "autostart": autostart(),
        "themerc-override": themerc_override(settings),
    }
    for name, content in files.items():
        path = target / name
        tmp = path.with_suffix(".tmp")
        tmp.write_text(content, encoding="utf-8")
        os.replace(tmp, path)
    os.chmod(target / "autostart", 0o755)
    return target


def _gsettings(schema, key, value):
    if not shutil.which("gsettings"):
        return
    subprocess.run(["gsettings", "set", schema, key, value],
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False)


def apply_gsettings(settings=None):
    settings = settings or load_file()
    dark = settings["appearance.app_mode"] == "dark"
    iface = "org.gnome.desktop.interface"
    _gsettings(iface, "gtk-theme", theme_name(settings))
    _gsettings(iface, "color-scheme", "prefer-dark" if dark else "default")
    _gsettings(iface, "font-name", "Selawik 10")
    _gsettings(iface, "document-font-name", "Selawik 10")
    _gsettings(iface, "cursor-theme", "DMZ-White")
    _gsettings(iface, "cursor-size", str(settings["appearance.cursor_size"]))
    _gsettings(iface, "text-scaling-factor", str(settings["appearance.text_scale"]))
    _gsettings(iface, "enable-animations", "true" if settings["appearance.animations"] else "false")
    _gsettings(iface, "clock-format", "24h" if settings["region.clock_24h"] else "12h")
    _gsettings(iface, "icon-theme", _icon_theme())
    _gsettings("org.gnome.desktop.wm.preferences", "button-layout", "'appmenu:minimize,maximize,close'")


def _icon_theme():
    for name in ("Yaru", "Adwaita"):
        if os.path.isdir("/usr/share/icons/%s" % name):
            return name
    return "hicolor"


def reconfigure_labwc():
    if os.environ.get("LABWC_PID"):
        subprocess.run(["labwc", "--reconfigure"], check=False,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def apply(settings=None):
    settings = settings or load_file()
    write_labwc_config(settings)
    apply_gsettings(settings)
    reconfigure_labwc()


def apply_outputs(settings=None):
    """Re-apply display modes saved by the Settings app (labwc doesn't persist them)."""
    from tenwin.services.display import apply_output
    settings = settings or load_file()
    for name, cfg in (settings["display.outputs"] or {}).items():
        if isinstance(cfg, dict):
            apply_output(name, cfg.get("width"), cfg.get("height"), None, cfg.get("scale"), cfg.get("transform"))


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    logging.basicConfig(level=logging.INFO, format="%(name)s: %(message)s")
    command = argv[0] if argv else "apply"
    if command == "prepare":
        settings = load_file()
        write_labwc_config(settings)
        apply_gsettings(settings)
        print(paths.LABWC_CONFIG_DIR)
    elif command == "apply":
        apply()
    elif command == "outputs":
        apply_outputs()
    elif command == "print-rc":
        sys.stdout.write(rc_xml(load_file()))
    else:
        print("usage: python3 -m tenwin.session prepare|apply|outputs|print-rc", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
